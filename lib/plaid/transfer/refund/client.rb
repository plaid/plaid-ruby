        # Use the `/transfer/refund/create` endpoint to create a refund for a transfer. A transfer can be refunded if
        # the transfer was initiated in the past 180 days.
        #
        # Refunds come out of the available balance of the ledger used for the original debit transfer. If there are not
        # enough funds in the available balance to cover the refund amount, the refund will be rejected. Plaid does not
        # impose a hold time before a refund can be created; you do not need to wait for the original transfer to
        # settle.
        #
        # A refund can still be issued even if the Item's `access_token` is no longer valid (e.g. if the user revoked
        # OAuth consent or the Item was deleted via `/item/remove`), as long as the account and routing number pair used
        # to make the original transaction is still valid. A refund cannot be issued if the Item has an [invalidated
        # TAN](https://plaid.com/docs/auth/#tokenized-account-numbers), which can occur at Chase or PNC.
        #
        # @param request_options [Hash]
        # @param params [Plaid::Transfer::Refund::Types::TransferRefundCreateRequest]
        # @option request_options [String] :base_url
        # @option request_options [Hash{String => Object}] :additional_headers
        # @option request_options [Hash{String => Object}] :additional_query_parameters
        # @option request_options [Hash{String => Object}] :additional_body_parameters
        # @option request_options [Integer] :timeout_in_seconds
        #
        # @example
        #   client.transfer.refund.create(
        #     transfer_id: "transfer_id",
        #     amount: "amount",
        #     idempotency_key: "idempotency_key"
        #   )
        #
        # @return [Plaid::Types::TransferRefundCreateResponse]
        def create(request_options: {}, **params)
          params = Plaid::Internal::Types::Utils.normalize_keys(params)
          request = Plaid::Internal::JSON::Request.new(
            base_url: request_options[:base_url],
            method: "POST",
            path: "transfer/refund/create",
            body: Plaid::Transfer::Refund::Types::TransferRefundCreateRequest.new(params).to_h,
            request_options: request_options
          )
          begin
            response = @client.send(request)
          rescue Net::HTTPRequestTimeout
            raise Plaid::Errors::TimeoutError
          end
          code = response.code.to_i
          if code.between?(200, 299)
            begin
              (response.body.to_s.empty? ? nil : Plaid::Types::TransferRefundCreateResponse.load(response.body))
            rescue ::JSON::ParserError
              raise Plaid::Errors::ResponseError.new(response.body, code: code, headers: response.to_hash)
            end
          else
            error_class = Plaid::Errors::ResponseError.subclass_for_code(code)
            error_types = {
              400 => Plaid::Types::PlaidError,
              401 => Plaid::Types::PlaidError,
              429 => Plaid::Types::PlaidError,
              500 => Plaid::Types::PlaidError,
              (400..499) => Plaid::Types::PlaidError,
              (500..599) => Plaid::Types::PlaidError
            }
            error_body = Plaid::Errors::ResponseError.load_error_body(code, response.body, error_types)
            raise error_class.new(response.body, code: code, body: error_body, headers: response.to_hash)
          end
        end

