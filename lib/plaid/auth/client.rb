# frozen_string_literal: true

module Plaid
  module Auth
    class Client
      # @param client [Plaid::Internal::Http::RawClient]
      #
      # @return [void]
      def initialize(client:)
        @client = client
      end

      # The `/auth/get` endpoint returns the bank account and bank identification numbers (such as routing numbers, for
      # US accounts) associated with an Item's checking, savings, and cash management accounts, along with high-level
      # account data and balances when available.
      #
      # Versioning note: In API version 2017-03-08, the schema of the `numbers` object returned by this endpoint is
      # substantially different. For details, see [Plaid API
      # versioning](https://plaid.com/docs/api/versioning/#version-2018-05-22).
      #
      # @param request_options [Hash]
      # @param params [Plaid::Auth::Types::AuthGetRequest]
      # @option request_options [String] :base_url
      # @option request_options [Hash{String => Object}] :additional_headers
      # @option request_options [Hash{String => Object}] :additional_query_parameters
      # @option request_options [Hash{String => Object}] :additional_body_parameters
      # @option request_options [Integer] :timeout_in_seconds
      #
      # @example
      #   client.auth.get(access_token: "access_token")
      #
      # @return [Plaid::Types::AuthGetResponse]
      def get(request_options: {}, **params)
        params = Plaid::Internal::Types::Utils.normalize_keys(params)
        request = Plaid::Internal::JSON::Request.new(
          base_url: request_options[:base_url],
          method: "POST",
          path: "auth/get",
          body: Plaid::Auth::Types::AuthGetRequest.new(params).to_h,
          request_options: request_options
        )
        begin
          response = @client.send(request)
        rescue Net::HTTPRequestTimeout
          raise Plaid::Errors::TimeoutError
        end
        code = response.code.to_i
        if code.between?(200, 299)
          begin
            (response.body.to_s.empty? ? nil : Plaid::Types::AuthGetResponse.load(response.body))
          rescue ::JSON::ParserError
            raise Plaid::Errors::ResponseError.new(response.body, code: code, headers: response.to_hash)
          end
        else
          error_class = Plaid::Errors::ResponseError.subclass_for_code(code)
          error_types = {
            400 => Plaid::Types::PlaidError,
            401 => Plaid::Types::PlaidError,
            429 => Plaid::Types::PlaidError,
            500 => Plaid::Types::PlaidError,
            (400..499) => Plaid::Types::PlaidError,
            (500..599) => Plaid::Types::PlaidError
          }
          error_body = Plaid::Errors::ResponseError.load_error_body(code, response.body, error_types)
          raise error_class.new(response.body, code: code, body: error_body, headers: response.to_hash)
        end
      end

      # The `/auth/verify` endpoint verifies bank account and routing numbers and (optionally) account owner names
      # against Plaid's database via [Database Auth](https://plaid.com/docs/auth/coverage/database-auth/). It can be
      # used to verify account numbers that were not collected via the Plaid Link flow.
      #
      # This endpoint is currently in Early Availability; contact sales or your Plaid account manager to request access.
      #
      # @param request_options [Hash]
      # @param params [Plaid::Auth::Types::AuthVerifyRequest]
      # @option request_options [String] :base_url
      # @option request_options [Hash{String => Object}] :additional_headers
      # @option request_options [Hash{String => Object}] :additional_query_parameters
      # @option request_options [Hash{String => Object}] :additional_body_parameters
      # @option request_options [Integer] :timeout_in_seconds
      #
      # @example
      #   client.auth.verify(numbers: {
      #     ach: {
      #       account: "account",
      #       routing: "routing"
      #     }
      #   })
      #
      # @return [Plaid::Types::AuthVerifyResponse]
