      # The `/link/token/create` endpoint creates a `link_token`, which is required as a parameter when initializing
      # Link. Once Link has been initialized, it returns a `public_token`. For most Plaid products, the `public_token`
      # is saved and exchanged for an `access_token` via `/item/public_token/exchange` as part of the main Link flow.
      # For more details, see the [Link flow overview](https://plaid.com/docs/link/#link-flow-overview).
      #
      # A `link_token` generated by `/link/token/create` is also used to initialize other Link flows, such as the
      # [update mode](https://plaid.com/docs/link/update-mode) flow for tokens with expired credentials, or the Identity
      # Verification flow.
      #
      # @param request_options [Hash]
      # @param params [Plaid::Link::Types::LinkTokenCreateRequest]
      # @option request_options [String] :base_url
      # @option request_options [Hash{String => Object}] :additional_headers
      # @option request_options [Hash{String => Object}] :additional_query_parameters
      # @option request_options [Hash{String => Object}] :additional_body_parameters
      # @option request_options [Integer] :timeout_in_seconds
      #
      # @example
      #   client.link.create_token(
      #     client_name: "client_name",
      #     language: "language",
      #     country_codes: ["US"]
      #   )
      #
      # @return [Plaid::Types::LinkTokenCreateResponse]
      def create_token(request_options: {}, **params)
        params = Plaid::Internal::Types::Utils.normalize_keys(params)
        request = Plaid::Internal::JSON::Request.new(
          base_url: request_options[:base_url],
          method: "POST",
          path: "link/token/create",
          body: Plaid::Link::Types::LinkTokenCreateRequest.new(params).to_h,
          request_options: request_options
        )
        begin
          response = @client.send(request)
        rescue Net::HTTPRequestTimeout
          raise Plaid::Errors::TimeoutError
        end
        code = response.code.to_i
        if code.between?(200, 299)
          begin
            (response.body.to_s.empty? ? nil : Plaid::Types::LinkTokenCreateResponse.load(response.body))
          rescue ::JSON::ParserError
            raise Plaid::Errors::ResponseError.new(response.body, code: code, headers: response.to_hash)
          end
        else
          error_class = Plaid::Errors::ResponseError.subclass_for_code(code)
          error_types = {
            400 => Plaid::Types::PlaidError,
            401 => Plaid::Types::PlaidError,
            429 => Plaid::Types::PlaidError,
            500 => Plaid::Types::PlaidError,
            (400..499) => Plaid::Types::PlaidError,
            (500..599) => Plaid::Types::PlaidError
          }
          error_body = Plaid::Errors::ResponseError.load_error_body(code, response.body, error_types)
          raise error_class.new(response.body, code: code, body: error_body, headers: response.to_hash)
        end
      end

      # The `/link/token/get` endpoint gets information about a Link session, including all callbacks fired during the
      # session along with their metadata, including the public token. This endpoint is used with Link flows that don't
      # provide a public token via frontend callbacks, such as the [Hosted Link
      # flow](https://plaid.com/docs/link/hosted-link/) and the [Multi-Item Link
      # flow](https://plaid.com/docs/link/multi-item-link/). It also can be useful for debugging purposes.
      #
      # By default, this endpoint will only return complete event data for Hosted Link sessions. To use
      # `/link/token/get` to retrieve event data for non-Hosted-Link sessions, contact your account manager to request
      # that your account be enabled for Link events. If you do not have an account manager, you can submit this request
      # via a support ticket. Enablement for Link events will also cause you to receive additional webhooks related to
      # Link events, such as the `SESSION_FINISHED` and `EVENTS` webhook.
      #
      # When called with a delegated OAuth access token, this endpoint returns a reduced view of the session for the
      # delegate. Only `link_token`, `created_at`, `expiration`, and each session's `link_session_id`, `started_at`,
      # `finished_at`, and `results.item_add_results[].public_token` are populated; `public_token` holds the delegate's
      # own `delegated-public-` token, never the customer's public token. All other fields are withheld and carry no
      # information about the session: arrays such as `metadata.initial_products` and `item_add_results[].accounts` are
      # empty, fields such as `metadata.webhook` and `item_add_results[].institution` are `null`, and `user_id`,
      # `events`, `on_success`, `on_exit`, and `exit` are omitted. A delegated public token can be retrieved for 30
      # minutes after it is created. Item adds whose delegated public token is no longer available are omitted from
      # `item_add_results`, and if none remain the request fails with `INVALID_LINK_TOKEN`; start a new Link session to
      # continue.
      #
      # @param request_options [Hash]
      # @param params [Plaid::Link::Types::LinkTokenGetRequest]
      # @option request_options [String] :base_url
