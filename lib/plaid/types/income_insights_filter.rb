# frozen_string_literal: true

require_relative "../../plaid"

module Plaid
  module Types
    # Filters the returned income streams based on the specified income categories. If no filters are requested, streams
    # from the following default set of categories are returned:
    # - `EARNED_INCOME.*` (`EARNED_INCOME.SALARY`, `EARNED_INCOME.GIG_ECONOMY`, `EARNED_INCOME.SELF_EMPLOYED`)
    # - `BENEFITS.DISABILITY`
    # - `RETIREMENT.*` (`RETIREMENT.GOVERNMENT_DERIVED`, `RETIREMENT.PRIVATE_RETIREMENT`,
    # `RETIREMENT.PLAN_DISTRIBUTION`)
    #
    # The final list of income categories is generated by adding the `included_categories`, then removing the
    # `excluded_categories`. Priority is given to `excluded_categories` in the case of collisions.
    #
    # Filter patterns supported:
    # - `*`: All categories
    # - `PRIMARY.*`: All categories within the specified primary category
    # - `PRIMARY.SECONDARY`: A specific income category
    #
    # For a list of income categories, see the [Income V2 Category
    # Taxonomy](https://plaid.com/documents/income-v2-category-taxonomy.csv).
    class IncomeInsightsFilter < Internal::Types::Model
      field :included_categories, -> { Internal::Types::Array[String] }, optional: false, nullable: false

      field :excluded_categories, -> { Internal::Types::Array[String] }, optional: true, nullable: false
    end
  end
end
