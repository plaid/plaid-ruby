      # with an `access_token` to create a Link token for use with [update
      # mode](https://plaid.com/docs/link/update-mode).
      #
      # If you need your user to take action to restore or resolve an error associated with an Item, generate a public
      # token with the `/item/public_token/create` endpoint and then initialize Link with that `public_token`.
      #
      # A `public_token` is one-time use and expires after 30 minutes. You use a `public_token` to initialize Link in
      # [update mode](https://plaid.com/docs/link/update-mode) for a particular Item. You can generate a `public_token`
      # for an Item even if you did not use Link to create the Item originally.
      #
      # The `/item/public_token/create` endpoint is **not** used to create your initial `public_token`. If you have not
      # already received an `access_token` for a specific Item, use Link to obtain your `public_token` instead. See the
      # [Quickstart](https://plaid.com/docs/quickstart) for more information.
      #
      # @param request_options [Hash]
      # @param params [Plaid::Item::Types::ItemPublicTokenCreateRequest]
      # @option request_options [String] :base_url
      # @option request_options [Hash{String => Object}] :additional_headers
      # @option request_options [Hash{String => Object}] :additional_query_parameters
      # @option request_options [Hash{String => Object}] :additional_body_parameters
      # @option request_options [Integer] :timeout_in_seconds
      #
      # @example
      #   client.item.create_public_token(access_token: "access_token")
      #
      # @return [Plaid::Types::ItemPublicTokenCreateResponse]
      def create_public_token(request_options: {}, **params)
        params = Plaid::Internal::Types::Utils.normalize_keys(params)
        request = Plaid::Internal::JSON::Request.new(
          base_url: request_options[:base_url],
          method: "POST",
          path: "item/public_token/create",
          body: Plaid::Item::Types::ItemPublicTokenCreateRequest.new(params).to_h,
          request_options: request_options
        )
        begin
          response = @client.send(request)
        rescue Net::HTTPRequestTimeout
          raise Plaid::Errors::TimeoutError
        end
        code = response.code.to_i
        if code.between?(200, 299)
          begin
            (response.body.to_s.empty? ? nil : Plaid::Types::ItemPublicTokenCreateResponse.load(response.body))
          rescue ::JSON::ParserError
            raise Plaid::Errors::ResponseError.new(response.body, code: code, headers: response.to_hash)
          end
        else
          error_class = Plaid::Errors::ResponseError.subclass_for_code(code)
