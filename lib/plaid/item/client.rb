      # The `/item/remove` endpoint allows you to remove an Item. Once removed, the `access_token`, as well as any
      # processor tokens or bank account tokens associated with the Item, is no longer valid and cannot be used to
      # access any data that was associated with the Item.
      #
      # Calling `/item/remove` is a recommended best practice when offboarding users or if a user chooses to disconnect
      # an account linked via Plaid. For subscription products, such as Transactions, Liabilities, and Investments,
      # calling `/item/remove` is required to end subscription billing for the Item, unless the end user revoked
      # permission (e.g. via [https://my.plaid.com/](https://my.plaid.com/)). For more details, see [Subscription fee
      # model](https://plaid.com/docs/account/billing/#subscription-fee).
      #
      # On a Trial plan, calling `/item/remove` does not impact the number of remaining Trial Items (bank connections)
      # you have available.
